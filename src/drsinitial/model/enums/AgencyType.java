package drsinitial.model.enums;

/**
 * Defines the available emergency agency response types.
 *
 * This enum is used to classify response agencies according
 * to the type of emergency support they provide in the
 * Disaster Response System.
 *
 * @author Jerald Christopher Bucud
 */
public enum AgencyType {

    /**
     * Agency responsible for fire and rescue response.
     */
    FIRE_RESPONSE,

    /**
     * Agency responsible for medical and ambulance response.
     */
    MEDICAL_RESPONSE,

    /**
     * Agency responsible for safety, security, and law enforcement response.
     */
    SECURITY_RESPONSE
}